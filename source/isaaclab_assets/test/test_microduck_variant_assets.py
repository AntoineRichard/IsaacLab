@pytest.mark.parametrize("variant", VARIANTS)
def test_converter_world_contact_set_is_the_mjcfs_own(converter, mj_models, variant):
    """The world-contact set the conversion keeps is re-derived from each MJCF, not copied.

    The conversion has to name the colliders it keeps, because the importer represents no
    ``contype``/``conaffinity`` masks. This checks the names against the MJCF they claim to describe,
    which is the assertion that would have caught reusing the walking model's two soles here -- and
    the one that pins the head shells as world colliders rather than as ``self_collision_only`` geoms
    the conversion may disable.
    """
    import mujoco

    model = mj_models[variant]
    spec = converter.MICRODUCK_MODELS[variant]

    named, unnamed, self_collision_only = set(), set(), set()
    for index in range(model.ngeom):
        contype, conaffinity = int(model.geom_contype[index]), int(model.geom_conaffinity[index])
        if contype == 0 and conaffinity == 0:
            continue
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, index)
        mesh = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_MESH, int(model.geom_dataid[index]))
        assert int(model.geom_group[index]) == converter.MJCF_COLLISION_GEOM_GROUP
        if not (contype & 1 and conaffinity & 1):
            self_collision_only.add(mesh)
        elif name:
            named.add(name)
        else:
            unnamed.add(mesh)

    assert spec.world_collider_geom_names == named
    assert spec.world_collider_meshes == unnamed
    if variant in HEAD_COLLIDING_VARIANTS:
        assert spec.world_collider_meshes >= HEAD_SHELL_MESHES, "the head must be able to touch the ground"
    # a mesh shared with a self-collision-only collider would make the mesh rule keep both
    assert spec.world_collider_meshes.isdisjoint(self_collision_only)


@pytest.mark.parametrize("variant", VARIANTS)
def test_joint_names_match_mjcf(usd_articulations, mj_joints, variant):
    """Every MJCF hinge survives the conversion, with no extras and none silently dropped."""
