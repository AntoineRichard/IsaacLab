"""Tests for the MicroDuck robot models that are not the plain walking one.

``microduck_allcollisions.usd``, ``microduck_rollers.usd`` and ``microduck_walk_backlash.usd`` are
generated by ``scripts/tools/convert_microduck.py --model {allcollisions,rollers,walk_backlash}``
from ``robot_allcollisions.xml``, ``robot_allcollisions_rollers.xml`` and
``robot_walk_backlash.xml`` of
`pollen-robotics/microduck_rl <https://github.com/pollen-robotics/microduck_rl>`_. The walking model
and everything the four share is covered by ``test_microduck_asset.py``; this file covers what the
variants add:

* the all-collisions model's six extra world colliders, of which the three head shells on
  ``jaw_soft`` are the ones a task that rolls the robot over its head cannot do without;
* the roller model's four ``passive_*_wheel`` hinges, which the importer must not drop and the servo
  group must not drive -- 18 joints, 14 of them actuated;
* the backlash model's 14 ``passive_*_backlash`` gear-play hinges, which the importer does not drop
  but *deletes*: each shares a MJCF body with its servo joint, which UsdPhysics cannot express, and
  the importer's D6 collapse resolves the duplicate axis by discarding it. The conversion rebuilds
  them on intermediate bodies -- 28 joints, 14 of them actuated, and 29 bodies.

The plain walking asset is spawned alongside the variants as the reference the backlash model's
servo joints have to keep matching.

The inputs are not in the repository: USD files are excluded by ``.gitignore``, and the MJCFs are
fetched from the pinned upstream commit into a local cache. The tests skip unless both are present.
Generate the assets with the command above, or point ``MICRODUCK_MJCF_DIR`` at a directory holding
the upstream MJCFs.
"""

