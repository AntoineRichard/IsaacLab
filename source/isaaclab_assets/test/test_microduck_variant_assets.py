"""The backlash model's play hinges, one per servo, spelled with upstream's naming convention.

Built from the servo names rather than transcribed because the convention is the contract: the
actuator wiring resolves a servo's play hinge by this name, so a conversion that named them
differently would silently leave every servo without one.
"""

BACKLASH_DUMMY_BODIES = frozenset(f"{joint}_dummy" for joint in BACKLASH_JOINTS)
"""The intermediate bodies the conversion inserts to carry the play hinges."""

BACKLASH_LIMIT_DEG = 1.0
"""Half of the peak-to-peak play [deg] upstream authors, and the unit the converted USD is in."""

BACKLASH_LIMIT_RAD = np.deg2rad(BACKLASH_LIMIT_DEG)
"""The same half-play [rad], which is what the built articulation must report."""

BACKLASH_DUMMY_MASS = 1e-6
"""Mass [kg] of an intermediate body: the smallest MuJoCo accepts for a moving body."""

BACKLASH_DUMMY_INERTIA = 1e-9
"""Diagonal inertia [kg*m^2] of an intermediate body, on all three axes.

Pinned because it is a floor, not a preference: Newton's ``ModelBuilder.finalize`` validates inertia
against an absolute eigenvalue floor of 1e-10 and adds 1e-6 when it corrects, so an inertia authored
below the floor reaches the solver a thousand times *heavier* than the play DOF's own armature.
"""

PASSIVE_JOINTS = {
    "allcollisions": frozenset(),
    "rollers": PASSIVE_WHEEL_JOINTS,
    "walk_backlash": BACKLASH_JOINTS,
}
"""Per variant: the hinges its MJCF adds that no actuator group drives."""

UNLIMITED_JOINT_RANGE = 2.0 * np.pi
"""Range [rad] beyond which a joint limit cannot bind on a joint the MJCF leaves unlimited.

Newton has no unlimited revolute joint, so the wheels arrive with an enormous but finite range. A
full turn is the smallest bound that proves the limit is out of the way of a freely spinning wheel.
"""


