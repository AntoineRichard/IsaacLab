def test_backlash_limits_are_authored_in_degrees_and_read_in_radians(usd_articulations):
    """Each play hinge carries upstream's +/-1 degree of play, in the two units it is expressed in.

    Both ends are pinned together because the conversion writes ``physics:lowerLimit`` in *degrees*
    while the MJCF, the actuator wiring and every task term work in radians. A play range authored as
    if it were radians would be 57 times too wide and would still look plausible in the USD.
    """
    robot, stage = usd_articulations["walk_backlash"]
    joint_prims = _joint_prims(stage, robot.cfg.prim_path)
    limits = robot.data.joint_pos_limits.torch[0].cpu().numpy()
    assert set(joint_prims) >= BACKLASH_JOINTS

    for index, name in enumerate(robot.joint_names):
        if name not in BACKLASH_JOINTS:
            continue
        prim = joint_prims[name]
        assert prim.GetAttribute("physics:lowerLimit").Get() == pytest.approx(-BACKLASH_LIMIT_DEG), name
        assert prim.GetAttribute("physics:upperLimit").Get() == pytest.approx(BACKLASH_LIMIT_DEG), name
        assert limits[index, 0] == pytest.approx(-BACKLASH_LIMIT_RAD, abs=1e-6), name
        assert limits[index, 1] == pytest.approx(BACKLASH_LIMIT_RAD, abs=1e-6), name


def test_backlash_hinges_ride_on_one_intermediate_body_each(usd_articulations, mj_models):
    """The play hinges arrive on their own bodies, which is the whole reason they arrive at all.

    MuJoCo hangs a play hinge off the body its servo already moves; UsdPhysics reads two joints
    between one body pair as a parallel loop, so the conversion has to give each play hinge a body of
    its own. The count is therefore the MJCF's bodies plus one per hinge.
    """
    robot, _ = usd_articulations["walk_backlash"]
    # MuJoCo body 0 is the world body, which is not part of the articulation
    mjcf_bodies = mj_models["walk_backlash"].nbody - 1

    assert set(robot.body_names) & BACKLASH_DUMMY_BODIES == BACKLASH_DUMMY_BODIES
    assert robot.num_bodies == mjcf_bodies + len(BACKLASH_JOINTS)


def test_backlash_intermediate_bodies_are_dynamically_invisible(usd_articulations):
    """The inserted bodies are as light as both compilers accept, as authored and as built.

    Both ends are pinned because only the second one misbehaves: Newton's ``ModelBuilder.finalize``
    validates inertia against an absolute eigenvalue floor of 1e-10 and *adds* 1e-6 when it corrects,
    so an inertia authored below the floor silently reaches the solver a thousand times heavier than
    the play DOF's own armature -- while the USD still reads as authored.
    """
    robot, stage = usd_articulations["walk_backlash"]
    body_prims = {
        prim.GetName(): prim
        for prim in Usd.PrimRange(stage.GetPrimAtPath(robot.cfg.prim_path))
        if prim.HasAPI(UsdPhysics.RigidBodyAPI)
    }
    masses = robot.data.body_mass.torch[0].cpu().numpy()
    # the authored inertia is isotropic, so the world frame the built one is reported in is irrelevant
    inertias = robot.data.body_inertia.torch[0].cpu().numpy().reshape(robot.num_bodies, 3, 3)
    body_indices = {name: index for index, name in enumerate(robot.body_names)}

    for name in sorted(BACKLASH_DUMMY_BODIES):
        index = body_indices[name]
        mass_api = UsdPhysics.MassAPI(body_prims[name])
        assert mass_api.GetMassAttr().Get() == pytest.approx(BACKLASH_DUMMY_MASS, rel=1e-6), name
        assert list(mass_api.GetDiagonalInertiaAttr().Get()) == pytest.approx([BACKLASH_DUMMY_INERTIA] * 3), name
        assert masses[index] == pytest.approx(BACKLASH_DUMMY_MASS, rel=1e-3), name
        np.testing.assert_allclose(np.diag(inertias[index]), BACKLASH_DUMMY_INERTIA, rtol=1e-3, err_msg=name)


def test_backlash_servo_joints_match_the_plain_walk_asset(usd_articulations):
    """The play hinges are added to the walking plant; they do not change it.

    Each servo joint is re-parented onto its new intermediate body and retyped out of the D6 the
    importer collapsed it into, so what it carries is checked against the model this one is a twin of
    rather than only against the MJCF. The retype is asserted too: a servo left as a D6 would keep the
    unauthored ``rotZ`` limit and drive the collapse added.
    """
    robot, stage = usd_articulations["walk_backlash"]
    reference, _ = usd_articulations[REFERENCE_MODEL]
    servo_names = set(reference.joint_names)
    assert servo_names == set(robot.joint_names) - BACKLASH_JOINTS

    for field in ("joint_pos_limits", "joint_armature", "joint_effort_limits"):
        actual = dict(zip(robot.joint_names, getattr(robot.data, field).torch[0].cpu().numpy()))
        expected = dict(zip(reference.joint_names, getattr(reference.data, field).torch[0].cpu().numpy()))
        for name in servo_names:
            np.testing.assert_allclose(actual[name], expected[name], rtol=1e-6, err_msg=f"{field} of {name}")

    joint_prims = _joint_prims(stage, robot.cfg.prim_path)
    assert {joint_prims[name].GetTypeName() for name in servo_names} == {"PhysicsRevoluteJoint"}


